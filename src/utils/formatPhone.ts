// Формат номера в клубе: "+7 702 1234567" (код страны + 10 цифр).
//
// Инпут контролируемый, поэтому value на каждый вызов — это уже наш
// предыдущий рендер плюс правка пользователя (включая наш же префикс
// "+7 "). Раньше здесь сразу стрипались все нецифровые символы из всей
// строки — но "+7" сама содержит цифру "7", и она на каждый ре-рендер
// путалась с первой цифрой настоящего номера, из-за чего backspace
// переставал реально укорачивать номер. Поэтому сначала явно снимаем
// именно наш буквальный префикс "+7", и только остаток разбираем на цифры.
export function formatPhoneMask(value: string): string {
  const rest = value.startsWith("+7") ? value.slice(2) : value;
  let digits = rest.replace(/\D/g, "");

  // Если всё равно вставили номер целиком со своим кодом страны
  // ("87021234567"/"+77021234567" в пустое поле, без нашего префикса
  // выше) — отбрасываем лишнее спереди, а не срезаем начало настоящего
  // номера: казахстанские операторские коды сами начинаются на "7"
  // (700-778).
  if (digits.length > 10) {
    digits = digits.slice(-10);
  }
  if (digits.length === 0) return "";

  let result = "+7";
  result += ` ${digits.slice(0, 3)}`;
  if (digits.length > 3) result += ` ${digits.slice(3, 10)}`;
  return result;
}
