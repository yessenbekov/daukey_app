-- ============================================================================
-- Разрешаем пользователю создать себе profiles-запись, если её ещё нет.
-- ============================================================================
-- Нужно для случая, когда auth.users создаётся не через обычную регистрацию
-- (signUp), а через привязку существующего пользователя общего Supabase-
-- проекта к новому провайдеру (например, вход через Google для аккаунта,
-- уже существовавшего в kokpar-game/Shezhire) — в этом случае триггер
-- handle_new_user() не срабатывает (он висит на INSERT в auth.users, а тут
-- строка auth.users не создаётся заново), и без этой политики пользователь
-- бы навсегда завис в состоянии "профиль не найден".
--
-- WITH CHECK жёстко фиксирует role='owner' и status='pending' — то есть
-- даже если сам пользователь сформирует произвольный INSERT через клиент,
-- он не сможет вставить себе роль admin или статус approved напрямую,
-- только через существующую логику одобрения админом.
-- ============================================================================

begin;

create policy profiles_insert_self on profiles
  for insert
  with check (
    auth.uid() = id
    and role = 'owner'
    and status = 'pending'
  );

commit;
